"""One results page for the whole project: reports/results/summary.md (Day 7).

Every day writes its own json (day03_baselines.json, day04_embeddings.json, ...). This module
reads them and puts the headline numbers in one place, so the README (Day 14) and interview prep
use exactly the numbers the code produced — no copying by hand.

It also checks PROVENANCE: every results file stores the fingerprint of the split it was computed
on. If two files disagree, their numbers are not comparable, and the summary says so loudly.
Smoke-run files (*_smoke.json) are ignored.
"""
from __future__ import annotations

from pathlib import Path

from . import config
from .experiment import md_table, read_results

FILES = {
    "day03": "day03_baselines.json",
    "day04": "day04_embeddings.json",
    "day05": "day05_retrieval.json",
    "day06": "day06_coldstart.json",
}
WARM_COLS = ["model", "config", "ndcg@5", "ndcg@10", "ndcg@20", "recall@10", "precision@10",
             "mrr@10", "coverage@10", "long_tail@10"]


def load_all(results_dir: Path | None = None) -> dict[str, dict]:
    return {day: read_results(name, results_dir) for day, name in FILES.items()}


def provenance(res: dict[str, dict]) -> tuple[bool, str]:
    """(all files on the same split?, markdown lines)."""
    prints = {day: r.get("split_fingerprint") for day, r in res.items() if r}
    distinct = {p for p in prints.values() if p}
    ok = len(distinct) <= 1 and all(prints.values())
    lines = [f"- `{FILES[d]}`: split `{(p or 'MISSING')[:12]}…`" for d, p in prints.items()]
    head = ("All results were computed on the same frozen split ✓" if ok else
            "⚠️ RESULTS COME FROM DIFFERENT SPLITS — re-run the older ones before comparing")
    return ok, head + "\n\n" + "\n".join(lines) + "\n"


def warm_rows(res: dict[str, dict]) -> list[dict]:
    """Test rows (fit on train+val, all warm users): Day 3 baselines + Day 5 embeddings."""
    rows = [dict(r) for r in res["day03"].get("test", {}).get("rows", [])]
    rows += [dict(r) for r in res["day05"].get("test", {}).get("rows", [])]
    pop = next((r["ndcg@10"] for r in rows if r["model"] == "popularity"), None)
    for r in rows:
        if pop:
            r["vs popularity"] = f"{100 * (r['ndcg@10'] / pop - 1):+.1f}%"
    return rows


def cold_table(res: dict[str, dict]) -> list[dict]:
    """NDCG@10 per number of onboarding seeds, one column per model (Day 6 test)."""
    test = res["day06"].get("test", {})
    tfidf = test.get("tfidf_day3", {})
    out = []
    for n in config.COLD_SEED_COUNTS:
        setting = f"seeds_{n}"
        line = {"seeds": n}
        for r in test.get("rows", []):
            if r.get("setting") == setting:
                line[r["model"]] = r["ndcg@10"]
        if str(n) in tfidf:
            line["TF-IDF (Day 3)"] = tfidf[str(n)]["ndcg@10"]
        out.append(line)
    return out


def significance_rows(res: dict[str, dict]) -> list[dict]:
    rows = []
    for s in res["day06"].get("test", {}).get("significance", []):
        lo, hi = s["ci95"]
        rows.append({"model": s["model"], "setting": s["setting"], "vs": s["vs"],
                     "change": f"{100 * s['rel_change']:+.1f}%",
                     "95% CI of diff": f"[{lo:+.4f}, {hi:+.4f}]", "p(≤0)": s["p_le_0"],
                     "significant": "yes" if s["p_le_0"] < 0.05 and lo > 0 else "no"})
    return rows


def build_summary(results_dir: Path | None = None) -> str:
    res = load_all(results_dir)
    md = "# Results summary\n\n"
    md += ("Generated by `python scripts/summarize_results.py` from the per-day json files in "
           "`reports/results/` — do not edit by hand. Relevant = rating ≥ 4.\n\n")
    _, prov = provenance(res)
    md += "## Provenance\n\n" + prov + "\n"

    warm = warm_rows(res)
    if warm:
        n = res["day03"].get("test", {}).get("n_users") or res["day05"].get("test", {}).get("n_users")
        md += f"## Warm users — test (fit on train+val, {n:,} users)\n\n"
        md += md_table(warm, WARM_COLS + ["vs popularity"]) + "\n"

    cold = cold_table(res)
    if any(len(c) > 1 for c in cold):
        n = res["day06"]["test"].get("n_users", 0)
        models = sorted({k for c in cold for k in c if k != "seeds"},
                        key=lambda m: ("popularity" not in m, "ours" in m, m))
        md += f"## Cold-start users — {n:,} users never in training (NDCG@10)\n\n"
        md += md_table(cold, ["seeds"] + models) + "\n"
        sig = significance_rows(res)
        if sig:
            md += "Paired bootstrap vs popularity (resampling users):\n\n"
            md += md_table(sig, ["model", "setting", "vs", "change", "95% CI of diff", "p(≤0)",
                                 "significant"], left=("model", "setting", "vs")) + "\n"

    cand = res["day05"].get("candidates", {})
    if cand.get("rows"):
        md += f"## Stage-1 retrieval — validation ({cand['n_users']:,} users)\n\n"
        cols = ["retriever"] + [f"recall@{k}" for k in config.CANDIDATE_BUDGETS]
        md += md_table(cand["rows"], cols, left=("retriever",))
        if "overlap@200" in cand:
            md += f"\nOverlap of the two top-200 lists: {100 * cand['overlap@200']:.1f}%.\n"
        md += "\n"

    ann = res["day05"].get("ann", {})
    if ann.get("recommended"):
        md += (f"## FAISS Flat vs HNSW — {ann['n_items']:,} × {ann['dim']} vectors, "
               f"{ann['threads']} thread\n\n")
        md += "| top-k | HNSW setting | recall vs exact | p95 ms | speed-up vs Flat |\n|---:|---|---:|---:|---:|\n"
        for k, r in ann["recommended"].items():
            md += (f"| {k} | M={r['M']}, ef_search={r['ef_search']} | {r['recall']:.3f} | "
                   f"{r['p95_ms']:.2f} | {r['speedup_p95_vs_flat']}× |\n")
        md += "\n"

    lat = res["day06"].get("latency_ms", {})
    if lat:
        md += "## Cold-start request latency (one request, CPU)\n\n| request | p50 ms | p95 ms |\n|---|---:|---:|\n"
        for name, v in lat.items():
            md += f"| {name} | {v['p50']:.1f} | {v['p95']:.1f} |\n"
        md += "\n"

    md += cv_status(res)
    return md


def cv_status(res: dict[str, dict]) -> str:
    """What the numbers support so far, per CV bullet (facts only, no rounding up)."""
    md = "## CV bullets — what the numbers support so far\n\n"
    sig = [s for s in res["day06"].get("test", {}).get("significance", [])
           if s["model"].endswith("(ours)") and s["setting"].startswith("seeds_")]
    good = [s for s in sig if s["p_le_0"] < 0.05 and s["ci95"][0] > 0]
    if good:
        best = max(good, key=lambda s: s["rel_change"])
        md += (f"1. Cold start: **{100 * best['rel_change']:+.1f}% NDCG@10** over popularity with "
               f"{best['setting'].split('_')[1]} onboarding picks (p = {best['p_le_0']}, "
               f"{res['day06']['test'].get('n_users', 0):,} held-out users). ✓\n")
    else:
        md += "1. Cold start: no significant gain over popularity yet.\n"
    md += "2. Two-stage retrieval & ranking: retrieval measured (Day 5); ranker pending (Days 8–9).\n"
    pop = next((r["ndcg@10"] for r in res["day03"].get("test", {}).get("rows", [])
                if r["model"] == "popularity"), None)
    if pop:
        md += (f"3. Warm-user NDCG@10 vs popularity: baseline **{pop:.4f}**; the final number comes "
               f"from the Day 10 ranker (a +12% claim would need ≥ {1.12 * pop:.4f}).\n")
    md += ("4. Benchmark: NDCG / Recall / Precision / MRR @5/10/20 vs popularity and TF-IDF — "
           "tables above; final table Day 10.\n")
    return md


def write_summary(results_dir: Path | None = None) -> Path:
    path = (results_dir or config.RESULTS_DIR) / "summary.md"
    path.write_text(build_summary(results_dir), encoding="utf-8")
    return path
