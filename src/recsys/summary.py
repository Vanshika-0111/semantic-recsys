"""One results page for the whole project: reports/results/summary.md (Day 7).

Every day writes its own json (day03_baselines.json, day04_embeddings.json, ...). This module
reads them and puts the headline numbers in one place, so the README (Day 14) and interview prep
use exactly the numbers the code produced — no copying by hand.

It also checks PROVENANCE: every results file stores the fingerprint of the split it was computed
on. If two files disagree, their numbers are not comparable, and the summary says so loudly.
Smoke-run files (*_smoke.json) are ignored.
"""
from __future__ import annotations

from pathlib import Path

from . import config
from .experiment import md_table, read_results

FILES = {
    "day03": "day03_baselines.json",
    "day04": "day04_embeddings.json",
    "day05": "day05_retrieval.json",
    "day06": "day06_coldstart.json",
    "day08": "day08_candidates.json",
    "day09": "day09_ranker.json",
    "day10": "day10_final.json",
    "day11": "day11_diversity.json",
}
WARM_COLS = ["model", "config", "ndcg@5", "ndcg@10", "ndcg@20", "recall@10", "precision@10",
             "mrr@10", "coverage@10", "long_tail@10"]


def load_all(results_dir: Path | None = None) -> dict[str, dict]:
    return {day: read_results(name, results_dir) for day, name in FILES.items()}


def provenance(res: dict[str, dict]) -> tuple[bool, str]:
    """(all files on the same split?, markdown lines)."""
    prints = {day: r.get("split_fingerprint") for day, r in res.items() if r}
    distinct = {p for p in prints.values() if p}
    ok = len(distinct) <= 1 and all(prints.values())
    lines = [f"- `{FILES[d]}`: split `{(p or 'MISSING')[:12]}…`" for d, p in prints.items()]
    head = ("All results were computed on the same frozen split ✓" if ok else
            "⚠️ RESULTS COME FROM DIFFERENT SPLITS — re-run the older ones before comparing")
    return ok, head + "\n\n" + "\n".join(lines) + "\n"


def warm_rows(res: dict[str, dict]) -> list[dict]:
    """Test rows (fit on train+val, all warm users): Day 3 baselines + Day 5 embeddings."""
    rows = [dict(r) for r in res["day03"].get("test", {}).get("rows", [])]
    rows += [dict(r) for r in res["day05"].get("test", {}).get("rows", [])]
    pop = next((r["ndcg@10"] for r in rows if r["model"] == "popularity"), None)
    for r in rows:
        if pop:
            r["vs popularity"] = f"{100 * (r['ndcg@10'] / pop - 1):+.1f}%"
    return rows


def cold_table(res: dict[str, dict]) -> list[dict]:
    """NDCG@10 per number of onboarding seeds, one column per model (Day 6 test)."""
    test = res["day06"].get("test", {})
    tfidf = test.get("tfidf_day3", {})
    out = []
    for n in config.COLD_SEED_COUNTS:
        setting = f"seeds_{n}"
        line = {"seeds": n}
        for r in test.get("rows", []):
            if r.get("setting") == setting:
                line[r["model"]] = r["ndcg@10"]
        if str(n) in tfidf:
            line["TF-IDF (Day 3)"] = tfidf[str(n)]["ndcg@10"]
        out.append(line)
    return out


def significance_rows(res: dict[str, dict]) -> list[dict]:
    rows = []
    for s in res["day06"].get("test", {}).get("significance", []):
        lo, hi = s["ci95"]
        rows.append({"model": s["model"], "setting": s["setting"], "vs": s["vs"],
                     "change": f"{100 * s['rel_change']:+.1f}%",
                     "95% CI of diff": f"[{lo:+.4f}, {hi:+.4f}]", "p(≤0)": s["p_le_0"],
                     "significant": "yes" if s["p_le_0"] < 0.05 and lo > 0 else "no"})
    return rows


def build_summary(results_dir: Path | None = None) -> str:
    res = load_all(results_dir)
    md = "# Results summary\n\n"
    md += ("Generated by `python scripts/summarize_results.py` from the per-day json files in "
           "`reports/results/` — do not edit by hand. Relevant = rating ≥ 4.\n\n")
    _, prov = provenance(res)
    md += "## Provenance\n\n" + prov + "\n"

    warm = warm_rows(res)
    if warm:
        n = res["day03"].get("test", {}).get("n_users") or res["day05"].get("test", {}).get("n_users")
        md += f"## Warm users — test (fit on train+val, {n:,} users)\n\n"
        md += md_table(warm, WARM_COLS + ["vs popularity"]) + "\n"

    cold = cold_table(res)
    if any(len(c) > 1 for c in cold):
        n = res["day06"]["test"].get("n_users", 0)
        models = sorted({k for c in cold for k in c if k != "seeds"},
                        key=lambda m: ("popularity" not in m, "ours" in m, m))
        md += f"## Cold-start users — {n:,} users never in training (NDCG@10)\n\n"
        md += md_table(cold, ["seeds"] + models) + "\n"
        sig = significance_rows(res)
        if sig:
            md += "Paired bootstrap vs popularity (resampling users):\n\n"
            md += md_table(sig, ["model", "setting", "vs", "change", "95% CI of diff", "p(≤0)",
                                 "significant"], left=("model", "setting", "vs")) + "\n"

    cand = res["day05"].get("candidates", {})
    if cand.get("rows"):
        md += f"## Stage-1 retrieval — validation ({cand['n_users']:,} users)\n\n"
        cols = ["retriever"] + [f"recall@{k}" for k in config.CANDIDATE_BUDGETS]
        md += md_table(cand["rows"], cols, left=("retriever",))
        if "overlap@200" in cand:
            md += f"\nOverlap of the two top-200 lists: {100 * cand['overlap@200']:.1f}%.\n"
        md += "\n"

    d8 = res.get("day08", {})
    if d8.get("test", {}).get("rows"):
        t, sel = d8["test"], d8.get("selected", {})
        md += (f"## Stage-1 candidates for the ranker — test ({t['n_users']:,} users, Day 8)\n\n"
               f"Popular top-{t['candidates']['pop']} ∪ FAISS top-{t['candidates']['faiss']}, chosen on "
               f"validation ({sel.get('rule', '')}).\n\n")
        md += md_table(t["rows"], ["candidates", "recall", "hit_rate"], left=("candidates",))
        f = d8.get("features", {})
        if f.get("one_feature"):
            orc = next((r["ndcg@10"] for r in f["one_feature"] if r["feature"] == "(oracle)"), None)
            if orc is not None:
                md += (f"\nCeiling for the ranker on validation (relevant candidates first): "
                       f"NDCG@10 = {orc:.4f}.\n")
        md += "\n"

    md += ranker_section(res)
    md += final_section(res)
    md += diversity_section(res)

    ann = res["day05"].get("ann", {})
    if ann.get("recommended"):
        md += (f"## FAISS Flat vs HNSW — {ann['n_items']:,} × {ann['dim']} vectors, "
               f"{ann['threads']} thread\n\n")
        md += "| top-k | HNSW setting | recall vs exact | p95 ms | speed-up vs Flat |\n|---:|---|---:|---:|---:|\n"
        for k, r in ann["recommended"].items():
            md += (f"| {k} | M={r['M']}, ef_search={r['ef_search']} | {r['recall']:.3f} | "
                   f"{r['p95_ms']:.2f} | {r['speedup_p95_vs_flat']}× |\n")
        md += "\n"

    lat = res["day06"].get("latency_ms", {})
    if lat:
        md += "## Cold-start request latency (one request, CPU)\n\n| request | p50 ms | p95 ms |\n|---|---:|---:|\n"
        for name, v in lat.items():
            md += f"| {name} | {v['p50']:.1f} | {v['p95']:.1f} |\n"
        md += "\n"

    md += cv_status(res)
    return md


def ranker_section(res: dict[str, dict]) -> str:
    """Day 9: ranker vs popularity on ranker-valid users (validation; test is Day 10)."""
    t = res.get("day09", {}).get("train", {})
    if not t.get("rows"):
        return ""
    sel = res["day09"].get("selected", {})
    md = (f"## Stage 2: LightGBM ranker — validation ({t['n_valid_users']:,} ranker-valid users, Day 9)\n\n"
          f"Selected: {sel.get('label', '')}, {sel.get('config', {}).get('labels', '')} labels, "
          f"{sel.get('config', {}).get('num_leaves', '')} leaves, {sel.get('best_iter', '')} trees. "
          "Test numbers come on Day 10.\n\n")
    md += md_table(t["rows"], ["model", "config", "ndcg@5", "ndcg@10", "ndcg@20", "recall@10", "mrr@10"])
    sig = [{"model": s["model"], "vs": s["vs"], "change": f"{100 * s['rel_change']:+.1f}%",
            "95% CI of diff": f"[{s['ci95'][0]:+.4f}, {s['ci95'][1]:+.4f}]", "p(≤0)": s["p_le_0"]}
           for s in t.get("significance", [])]
    if sig:
        md += "\n" + md_table(sig, ["model", "vs", "change", "95% CI of diff", "p(≤0)"], left=("model", "vs"))
    c = res["day09"].get("cold", {})
    if c.get("rows"):
        md += f"\nCold mode (pseudo-cold validation, {c['n_valid_users']:,} users), NDCG@10:\n\n"
        models = list(dict.fromkeys(r["model"] for r in c["rows"]))
        table = []
        for n in sorted({r["seeds"] for r in c["rows"]}):
            line = {"seeds": n}
            for r in c["rows"]:
                if r["seeds"] == n:
                    line[r["model"]] = r["ndcg@10"]
            table.append(line)
        md += md_table(table, ["seeds"] + models)
    return md + "\n"


def _sig_lines(sigs: list[dict], first: tuple = ()) -> str:
    rows = [{**s, "change": f"{100 * s['rel_change']:+.1f}%",
             "95% CI of diff": f"[{s['ci95'][0]:+.4f}, {s['ci95'][1]:+.4f}]", "p(≤0)": s["p_le_0"],
             "significant": "yes" if s["p_le_0"] < 0.05 and s["ci95"][0] > 0 else "no"} for s in sigs]
    return md_table(rows, list(first) + ["model", "vs", "change", "95% CI of diff", "p(≤0)", "significant"],
                    left=("model", "vs"))


def final_section(res: dict[str, dict]) -> str:
    """Day 10: the locked test numbers (warm + cold), ablations and SHAP groups."""
    d = res.get("day10", {})
    if not d:
        return ""
    md = ""
    t = d.get("test", {})
    if t.get("rows"):
        pop = t["rows"][0]["ndcg@10"]
        rows = [{**r, "vs popularity": f"{100 * (r['ndcg@10'] / pop - 1):+.1f}%"} for r in t["rows"]]
        md += (f"## FINAL — warm users, test ({t['n_users']:,} users, Day 10)\n\n"
               "Ranker trained on validation (Day 9), stage 1 + features fit on train+val, scored once on test.\n\n")
        md += md_table(rows, ["model", "ndcg@5", "ndcg@10", "ndcg@20", "recall@10", "precision@10", "mrr@10",
                              "coverage@10", "vs popularity"]) + "\n"
        md += _sig_lines([s for s in t["significance"] if s["model"].endswith("(ours)")]) + "\n"
    ab = d.get("ablation", {})
    if ab.get("rows"):
        md += (f"Ablations (validation, {ab['n_valid_users']:,} users; same split + config, feature set "
               "removed):\n\n" + md_table(ab["rows"], ["model", "candidates", "features", "ndcg@10"],
                                         left=("model", "candidates")) + "\n")
    c = d.get("cold", {})
    if c.get("rows"):
        table = {}
        for r in c["rows"]:
            table.setdefault(r["seeds"], {"seeds": r["seeds"]})[r["model"]] = r["ndcg@10"]
        models = list(dict.fromkeys(r["model"] for r in c["rows"]))
        md += (f"## FINAL — real cold-start users, test ({c['n_users']:,} users, Day 10), NDCG@10\n\n"
               + md_table(list(table.values()), ["seeds"] + models) + "\n")
        md += _sig_lines([s for s in c["significance"] if s["model"] == "policy (ours)"], ("seeds",)) + "\n"
    sh = d.get("shap", {})
    if sh.get("groups_all"):
        md += (f"SHAP ({sh['n_users']:,} test users), share of mean |SHAP|: "
               + ", ".join(f"{g['group']} {100 * g['share']:.0f}%" for g in sh["groups_all"]) + ".\n\n")
    return md


def diversity_section(res: dict[str, dict]) -> str:
    """Day 11: MMR accuracy-vs-diversity at the validation-chosen λ, and explanation faithfulness."""
    d = res.get("day11", {})
    t = d.get("test", {})
    if not t.get("rows"):
        return ""
    sel = t["selected"]
    keep = [r for r in t["rows"] if r["model"] == "popularity" or (r.get("space") == "embedding" and r["lambda"] == 1.0)
            or (r.get("space") == sel["space"] and r["lambda"] == sel["lambda"])]
    md = (f"## Diversity — MMR re-ranking, test ({t['n_users']:,} users, Day 11)\n\n"
          f"Chosen on validation: {sel['space']} similarity, λ {sel['lambda']} (most diverse setting within "
          f"{100 * config.MMR_MAX_NDCG_LOSS:.0f}% of the ranker's NDCG@10).\n\n")
    md += md_table(keep, ["model", "lambda", "ndcg@10", "recall@10", "coverage@10", "genre_div@10", "sem_div@10",
                          "genres@10"]) + "\n"
    sig = [s for s in t.get("significance", []) if s.get("selected")]
    if sig:
        md += "Selected MMR vs the ranker (paired bootstrap): " + "; ".join(
            f"{s['metric']} {100 * s['rel_change']:+.1f}% [CI {s['ci95'][0]:+.4f}, {s['ci95'][1]:+.4f}]" for s in sig) + ".\n\n"
    cf = d.get("explain", {}).get("counterfactual")
    if cf:
        md += (f"Explanations: \"Because you liked X\" available for {100 * d['explain']['because_share']:.0f}% of served "
               f"recommendations. Removing the cited X lowers the movie's score by {cf['cited']['mean_score_drop']:.3f} "
               f"(rank {cf['cited']['mean_rank_change']:+.1f}) vs {cf['control']['mean_score_drop']:.3f} "
               f"(rank {cf['control']['mean_rank_change']:+.1f}) for a random other recent like "
               f"({cf['n_pairs']:,} recommendations).\n\n")
    return md


def _final_sig(res: dict[str, dict], model: str, vs_prefix: str, seeds=None) -> dict | None:
    d = res.get("day10", {})
    part = d.get("cold" if seeds is not None else "test", {})
    for s in part.get("significance", []):
        if s["model"] == model and s["vs"].startswith(vs_prefix) and (seeds is None or s.get("seeds") == seeds):
            return s
    return None


def ranker_status(res: dict[str, dict]) -> str:
    sel = res.get("day09", {}).get("selected", {})
    if not sel:
        return "ranker pending (Day 9)."
    done = "tested on Day 10 (below)" if res.get("day10", {}).get("test") else "test on Day 10"
    return (f"ranker ✓ (Day 9, validation): {sel['label']} chosen end to end; {done}.")


def cv_status(res: dict[str, dict]) -> str:
    """What the numbers support so far, per CV bullet (facts only, no rounding up)."""
    md = "## CV bullets — what the numbers support so far\n\n"
    sig = [s for s in res["day06"].get("test", {}).get("significance", [])
           if s["model"].endswith("(ours)") and s["setting"].startswith("seeds_")]
    good = [s for s in sig if s["p_le_0"] < 0.05 and s["ci95"][0] > 0]
    if good:
        best = max(good, key=lambda s: s["rel_change"])
        md += (f"1. Cold start: **{100 * best['rel_change']:+.1f}% NDCG@10** over popularity with "
               f"{best['setting'].split('_')[1]} onboarding picks (p = {best['p_le_0']}, "
               f"{res['day06']['test'].get('n_users', 0):,} held-out users). ✓\n")
    else:
        md += "1. Cold start: no significant gain over popularity yet.\n"
    for n in (1, 3, 5):
        s = _final_sig(res, "policy (ours)", "popularity", n)
        if s:
            md += (f"   - Day 10 policy (two-stage ranker for new users), {n} picks: "
                   f"**{100 * s['rel_change']:+.1f}%** vs popularity (p = {s['p_le_0']}, "
                   f"{'significant' if s['p_le_0'] < 0.05 and s['ci95'][0] > 0 else 'not significant'})\n")
    t8 = res.get("day08", {}).get("test", {})
    if t8.get("rows"):
        u = t8["rows"][0]
        same = next((r for r in t8["rows"] if "same size" in r["candidates"]), None)
        md += (f"2. Two-stage retrieval & ranking: stage 1 = {u['candidates'].split(': ')[-1]}, test recall "
               f"{u['recall']:.4f}" + (f" (popularity alone at the same size: {same['recall']:.4f})"
                                        if same else "") + "; " + ranker_status(res) + "\n")
    else:
        md += "2. Two-stage retrieval & ranking: retrieval measured (Day 5); ranker pending (Days 8–9).\n"
    pop = next((r["ndcg@10"] for r in res["day03"].get("test", {}).get("rows", [])
                if r["model"] == "popularity"), None)
    if pop:
        sel = res.get("day09", {}).get("selected", {})
        val = (f" Day 9 validation: ranker {sel['val_ndcg@10']:.4f} vs popularity "
               f"{res['day09']['train']['rows'][0]['ndcg@10']:.4f} on the same users "
               f"({100 * (sel['val_ndcg@10'] / res['day09']['train']['rows'][0]['ndcg@10'] - 1):+.1f}%)."
               if sel and res["day09"].get("train") else "")
        md += (f"3. Warm-user NDCG@10 vs popularity: test baseline **{pop:.4f}**; the CV number comes "
               f"from the Day 10 test run (a +12% claim would need ≥ {1.12 * pop:.4f}).{val}\n")
    s = _final_sig(res, "two-stage ranker (ours)", "popularity")
    if s:
        rel = _final_sig(res, "two-stage ranker (ours)", "release-aware")
        nosem = _final_sig(res, "two-stage ranker (ours)", "ranker w/o any semantics")
        md += (f"   - **Day 10 TEST: ranker {s['mean_a']:.4f} vs popularity {s['mean_b']:.4f} = "
               f"{100 * s['rel_change']:+.1f}%** (p = {s['p_le_0']}, {s['n_users']:,} users)"
               + (f"; vs release-aware popularity {100 * rel['rel_change']:+.1f}%" if rel else "")
               + (f"; semantic part (vs the same ranker with no embeddings anywhere) "
                  f"{100 * nosem['rel_change']:+.1f}% (p = {nosem['p_le_0']})" if nosem else "") + "\n")
    md += ("4. Benchmark: NDCG / Recall / Precision / MRR @5/10/20 vs popularity and TF-IDF — "
           + ("final test table above (Day 10) ✓.\n" if s else "tables above; final table Day 10.\n"))
    return md


def write_summary(results_dir: Path | None = None) -> Path:
    path = (results_dir or config.RESULTS_DIR) / "summary.md"
    path.write_text(build_summary(results_dir), encoding="utf-8")
    return path
